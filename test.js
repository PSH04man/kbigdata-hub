// node test.js — 이름·클래스 교체 자체 검사
require("./lib.js");
const assert = require("assert");
const { KB } = globalThis;

assert.strictEqual(KB.idName("JAVA-030"), "Main030");
assert.strictEqual(KB.idName("JAVA-031"), "Main031");
assert.strictEqual(KB.idName("X"), "Main");
assert.strictEqual(KB.renameClass("import x;\npublic class Main {\n}", "Tri"), "import x;\npublic class Tri {\n}");
assert.strictEqual(KB.renameClass("class A {}", "Tri"), "class A {}");
assert.strictEqual(Buffer.from(KB.base64("한글 a"), "base64").toString(), "한글 a");
assert.ok(KB.explain("GitHub", 999).includes("알 수 없는"));
assert.strictEqual(KB.dirName("JAVA-030", "삼각형 성립 여부"), "JAVA-030. 삼각형 성립 여부");
assert.strictEqual(KB.dirName("JAVA-031", "a/b: c?"), "JAVA-031. a b c");
assert.strictEqual(KB.dirName("JAVA-032", "끝에 점..."), "JAVA-032. 끝에 점");
assert.strictEqual(KB.dirName("JAVA-033", "JAVA-033"), "JAVA-033");
assert.strictEqual(KB.dirName("JAVA-034", ""), "JAVA-034");
assert.ok(KB.readme({ id: "JAVA-030", title: "삼각형", url: "u", name: "Tri", date: "2026-11-25" }).includes("`Tri.java`"));
assert.strictEqual(KB.normRepo("PSH04man/Programmer"), "PSH04man/Programmer");
assert.strictEqual(KB.normRepo(" https://github.com/PSH04man/Programmer.git/ "), "PSH04man/Programmer");
assert.strictEqual(KB.normRepo("github.com/a/b"), "a/b");
assert.strictEqual(KB.normRepo("Programmer"), null);
assert.strictEqual(KB.normRepo("https://github.com/a/b/tree/main"), null);
assert.ok(KB.isKey("github_pat_ABC123"));
assert.ok(!KB.isKey("AIza키"));
assert.ok(!KB.isKey("abc def"));
assert.strictEqual(KB.renameClass("class Main{}", "Main031"), "class Main031{}");
assert.strictEqual(KB.renameClass("class MainHelper {}", "Main031"), "class MainHelper {}");
assert.strictEqual(KB.renameClass("class Main {} public class App {}", "Main031"), "class Main {} public class Main031 {}");
const md = KB.readme({ id: "JAVA-021", title: "홀짝", url: "u", name: "Main021", date: "d", problem: { level: "입문", topic: "조건문", statement: "a < b 이면 **x**", examples: [["-7", "ODD"], ["7", "ODD"]] } });
assert.ok(md.includes("[문제 링크](u) · 입문 · 조건문") && md.includes("## 문제") && md.includes("a \\< b 이면 \\*\\*x\\*\\*"));
assert.ok(md.includes("## 입출력 예제 2") && md.includes("```\n-7\n```") && md.includes("`Main021.java`"));
assert.ok(!KB.readme({ id: "i", title: "t", url: "u", name: "n", date: "d" }).includes("## 문제"));
assert.deepStrictEqual(["JAVA-001", "C-002", "PY-003", "LINUX-004", "SPRING-005"].map(i => KB.lang(i).ext), ["java", "c", "py", "sh", "txt"]);
assert.strictEqual(KB.folderFor("k-bigdataPortal/기초350/Java", "JAVA-001"), "k-bigdataPortal/기초350/Java");
assert.strictEqual(KB.folderFor("k-bigdataPortal/기초350/Java", "PY-001"), "k-bigdataPortal/기초350/Python");
assert.strictEqual(KB.folderFor("k-bigdataPortal/기초350/Java", "SPRING-1"), "k-bigdataPortal/기초350/SPRING");
assert.strictEqual(KB.folderFor("풀이", "C-001"), "풀이/C");
assert.ok(KB.readme({ id: "LINUX-001", title: "t", url: "u", name: "n", date: "d", ext: "sh", problem: { statement: "s", labels: ["초기 실행 환경", "예상 실행 결과"], examples: [["ls", "a"]] } }).includes("초기 실행 환경"));
assert.strictEqual(KB.renameClass('public class Main {\n  Main() {}\n  public static void main(String[] a) { Main m = new Main(); Main.run(); System.out.println("Main"); } // Main\n}', "Main031"),
  'public class Main031 {\n  Main031() {}\n  public static void main(String[] a) { Main031 m = new Main031(); Main031.run(); System.out.println("Main"); } // Main\n}');
assert.strictEqual(KB.renameClass("class Main { static Main x; } class MainHelper {}", "Q"), "class Q { static Q x; } class MainHelper {}");
assert.strictEqual(KB.renameClass('// class Main\nint x;', "Q"), '// class Main\nint x;');
assert.strictEqual(KB.fileName("valid_triangle", "py"), "valid_triangle");
assert.strictEqual(KB.fileName("main031.java"), "main031");
assert.strictEqual(KB.fileName("삼각형"), "삼각형");
assert.strictEqual(KB.fileName("my-answer", "c"), "my-answer");
assert.strictEqual(KB.fileName("my-answer", "java"), null);
assert.strictEqual(KB.fileName("1abc"), null);
assert.strictEqual(KB.fileName("../x", "sh"), null);
assert.ok(KB.friendly("Failed to fetch").includes("인터넷"));
assert.strictEqual(KB.friendly("GitHub 401: x"), "GitHub 401: x");
assert.ok(KB.readme({ id: "J-1", title: "a<b>c", url: "u", name: "n", date: "d" }).startsWith("# [J-1] a\\<b\\>c"));
assert.strictEqual(KB.idName("R-SQL-0019", "sql"), "Query0019");
assert.strictEqual(KB.folderFor("x/Java", "R-SQL-0019", "sql"), "k-bigdataPortal/정보처리실기/SQL");
assert.strictEqual(KB.freeName("Main003", []), "Main003");
assert.strictEqual(KB.freeName("Main003", ["main003"]), "Main003_2");
assert.strictEqual(KB.freeName("Main003_2", ["Main003", "Main003_2"]), "Main003_3");
assert.ok(KB.readme({ id: "i", title: "t", url: "u", name: "b", date: "d", names: ["a", "b"] }).includes("`a.java`, `b.java`"));
// "hello\n" 의 git blob sha (git hash-object 값)
assert.strictEqual(KB.webUrl("a/b"), "https://github.com/a/b");
assert.strictEqual(KB.webUrl("a/b", "dev/x", "폴더/A #1.java"), "https://github.com/a/b/blob/dev/x/%ED%8F%B4%EB%8D%94/A%20%231.java");
assert.strictEqual(KB.clash("Main003", "Main003_2", ["Main003", "Main003_2"]), true);
assert.strictEqual(KB.clash("main003", "Main003_2", ["Main003", "Main003_2"]), true);
assert.strictEqual(KB.clash("main003", "Main003", ["Main003"]), false);
assert.strictEqual(KB.clash("New", "Main003", ["Main003"]), false);
assert.strictEqual(KB.clash("Main003", undefined, ["Main003"]), false);
KB.blobSha("hello\n").then(sha => { assert.strictEqual(sha, "ce013625030ba8dba906f756967f9e9ca394464a"); console.log("ok"); });
